export function useTranslation() {
  const language = useAppStore((s) => s.language);
  const setLanguage = useAppStore((s) => s.setLanguage);
  return {
    lang: language,
    setLanguage,
    t: dict[language],
    tf: (en: string | undefined, ta: string | undefined) => tField(en, ta, language),
  };
}
